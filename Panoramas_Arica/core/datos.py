def filtrar_actividades(actividades, q="", modalidad="", participantes=""):
    resultado = actividades

    # 1) Texto libre: busca en título, descripción, lugar y etiquetas
    q = q.strip().lower()
    if q:
        resultado = [
            a for a in resultado
            if q in a["titulo"].lower()
            or q in a["descripcion"].lower()
            or q in a["lugar"].lower()
            or q in a.get("etiquetas", "").lower()
        ]

    # 2) Tipo de actividad: coincidencia exacta con el value del select
    if modalidad:
        resultado = [a for a in resultado if a["modalidad"] == modalidad]

    # 3) Cupos: solo actividades con al menos N cupos disponibles
    if participantes.isdigit():
        n = int(participantes)
        resultado = [a for a in resultado if a["cupos"] >= n]

    return resultado